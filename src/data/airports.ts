export function getAirportBySlug(slug: string): AirportData | undefined {
  return airportsData.find((a) => a.slug === slug || a.id === slug);
}

export function getTopAirports(limit: number = 10): AirportData[] {
  return [...airportsData].sort((a, b) => a.rank - b.rank).slice(0, limit);
}

export function getSpeedtestAirports(): AirportData[] {
  return airportsData.filter((a) => Boolean(a.speedtestImage || (a.unlockImages && a.unlockImages.length > 0)));
}
